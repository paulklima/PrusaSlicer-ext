#!/usr/bin/env bash
# Per-clone setup for the fork workflow (doc/FORK-WORKFLOW.md, "Tooling"). Idempotent;
# re-run after creating a new dev/fork line and after changes to the fork tooling.
#
# Installs everything outside the tracked tree, so it also works while a feature branch
# (based on a plain upstream tag, without scripts/ and CLAUDE.md) is checked out:
#   <git-common-dir>/fork-tools/fork-status.sh   status report
#   <git-common-dir>/fork-tools/fork-bump.sh     upgrade-all tool, alias 'git fork-bump'
#   .claude/settings.local.json                  Claude Code SessionStart hook running it
#   CLAUDE.local.md                              the "Fork workflow rules" from CLAUDE.md
# Sources: this checkout if it has them, else the newest dev/* line.
set -euo pipefail

root=$(git rev-parse --show-toplevel)
common=$(cd "$(git rev-parse --git-common-dir)" && pwd)

# fresh clone: local branches for the dev/* and fork/* lines of origin
for r in $(git for-each-ref --format='%(refname:short)' refs/remotes/origin/dev/ refs/remotes/origin/fork/); do
    l=${r#origin/}
    git rev-parse -q --verify "refs/heads/$l" >/dev/null || git branch -q --track "$l" "$r"
done
dev=$(git for-each-ref --sort=-version:refname --format='%(refname:short)' refs/heads/dev/ | head -1)

# fetch <path> <dest>: from the working tree, else from the newest dev line
fetch() {
    if [ -f "$root/$1" ]; then cp "$root/$1" "$2"
    elif [ -n "$dev" ]; then git show "$dev:$1" > "$2"
    else echo "fork-setup: $1 not found (no dev/* line)" >&2; return 1; fi
}

tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
fetch scripts/fork-status.sh "$tmp/fork-status.sh"
fetch scripts/fork-bump.sh "$tmp/fork-bump.sh"
fetch CLAUDE.md "$tmp/CLAUDE.md"

# git configuration: merge commits on the lines, rerere for repeated conflicts
for l in $(git for-each-ref --format='%(refname:short)' refs/heads/dev/ refs/heads/fork/); do
    git config "branch.$l.mergeoptions" --no-ff
done
git config pull.ff only
git config rerere.enabled true
git config gc.rerereResolved 3650
git config rebase.updateRefs true
git config --replace-all versionsort.suffix -rc.

# status script
mkdir -p "$common/fork-tools"
install -m 755 "$tmp/fork-status.sh" "$common/fork-tools/fork-status.sh"
install -m 755 "$tmp/fork-bump.sh" "$common/fork-tools/fork-bump.sh"
git config alias.fork-bump '!"$(git rev-parse --git-common-dir)/fork-tools/fork-bump.sh"'

# keep the local agent files out of git
exclude="$common/info/exclude"
mkdir -p "$(dirname "$exclude")"
for p in /.claude/settings.local.json /CLAUDE.local.md; do
    grep -qxF "$p" "$exclude" 2>/dev/null || echo "$p" >> "$exclude"
done

# Claude Code SessionStart hook (path-independent: host and sandbox mount the repo differently)
python3 - "$root/.claude/settings.local.json" <<'EOF'
import json, os, sys
path = sys.argv[1]
cmd = ('cd "$CLAUDE_PROJECT_DIR" && f="$(git rev-parse --git-common-dir)/fork-tools/fork-status.sh"; '
       '[ -x "$f" ] && "$f"; true')
os.makedirs(os.path.dirname(path), exist_ok=True)
data = {}
if os.path.exists(path):
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
starts = data.setdefault("hooks", {}).setdefault("SessionStart", [])
starts[:] = [s for s in starts if not any("fork-status.sh" in h.get("command", "") for h in s.get("hooks", []))]
starts.append({"matcher": "startup|resume|compact", "hooks": [{"type": "command", "command": cmd}]})
with open(path + ".tmp", "w", encoding="utf-8") as f:
    json.dump(data, f, indent=2, ensure_ascii=False)
    f.write("\n")
os.replace(path + ".tmp", path)
EOF

# CLAUDE.local.md: the binding rules, available on every branch (written only if non-empty)
rules=$(sed -n '/^## Fork workflow rules/,/^## /{/^## /!p;/^## Fork workflow rules/p}' "$tmp/CLAUDE.md")
if [ -n "$rules" ]; then
    {
        echo "<!-- Generated by scripts/fork-setup.sh from CLAUDE.md of the dev line - do not edit. -->"
        echo "# PrusaSlicer ext - fork workflow (local copy)"
        echo
        echo "Feature branches are based on plain upstream tags and do not contain the fork's CLAUDE.md"
        echo "or docs; the full reference is doc/FORK-WORKFLOW.md on the newest dev/* branch"
        echo "(\`git show dev/<version>:doc/FORK-WORKFLOW.md\`)."
        echo
        echo "$rules"
    } > "$tmp/CLAUDE.local.md"
    mv "$tmp/CLAUDE.local.md" "$root/CLAUDE.local.md"
else
    echo "fork-setup: no 'Fork workflow rules' section found, CLAUDE.local.md left unchanged" >&2
fi

echo "fork-setup: done ($(git for-each-ref --format='%(refname:short)' refs/heads/dev/ refs/heads/fork/ | tr '\n' ' '))"
"$common/fork-tools/fork-status.sh"
